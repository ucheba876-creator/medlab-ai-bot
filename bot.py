@router_dp.message(F.text)
async def on_text(message: Message, bot: Bot):
    if message.from_user is None:
        return
    uid = message.from_user.id
    text = (message.text or "").strip()
    if not text:
        return

    p, stage = get_ready_profile(uid)

    # Неизвестные команды (/help и т. п.)
    if text.startswith("/"):
        if p:
            await say(message, TEXTS[p["lang"]]["help"])
        else:
            await say(message, TEXTS["ru"]["help"] + "\n\n" + TEXTS["kk"]["help"])
        if stage != "ready":
            await stage_prompt(message, p, stage)
        return

    if stage in ("start", "sex"):
        await stage_prompt(message, p, stage)
        return

    t = TEXTS[p["lang"]]

    if stage == "age":
        m = re.search(r"\d{1,4}", text)
        age = int(m.group()) if m else None
        if age is None or not (18 <= age <= 25):
            await say(message, t["bad_age"])
            return
        p["age"] = age
        p["offtopic_count"] = 0
        await say(message, t["ask_analysis"])
        return

    # stage == "ready"
    fast_analysis = looks_like_analysis(text)
    if p.get("offtopic_count", 0) >= OFFTOPIC_LIMIT and not fast_analysis:
        # Режим приостановки: без обращения к Claude API
        await say(message, t["offtopic_blocked"])
        return

    lock = get_lock(uid)
    if lock.locked():
        await say(message, t["busy"])
        return
    async with lock:
        try:
            if fast_analysis:
                kind = "ANALYSIS"
            elif is_smalltalk(text):
                kind = "SMALLTALK"
            else:
                async with typing_indicator(bot, message.chat.id):
                    kind = await classify_text(p, text)

            if kind == "OFFTOPIC":
                p["offtopic_count"] = p.get("offtopic_count", 0) + 1
                await say(message, offtopic_text(t, p["offtopic_count"]))
            elif kind == "SMALLTALK":
                await say(message, t["smalltalk"])
            elif kind == "ANALYSIS":
                await respond_via_claude(
                    message, bot, p, uid, text, t["reminder_analysis"], text, mode="analysis",
                )
            else:  # QUESTION
                await respond_via_claude(
                    message, bot, p, uid, text, t["reminder_question"], text, mode="question",
                )
        except Exception as e:
            log.exception("Bot error: %s", describe_error(e))
            await say(message, err_text(t, e))


@router_dp.message()
async def on_other(message: Message):
    """Стикеры, голосовые, видео, аудио, GIF, контакты и т. п. — не молчим, а объясняем."""
    if message.from_user is None:
        return
    uid = message.from_user.id
    p, stage = get_ready_profile(uid)
    key = getattr(message.content_type, "value", str(message.content_type))

    if p:
        t = TEXTS[p["lang"]]
        await say(message, t["unsupported_kind"].format(kind=t["kinds"].get(key, t["kinds"]["other"])))
    else:
        ru, kk = TEXTS["ru"], TEXTS["kk"]
        await say(
            message,
            ru["unsupported_kind"].format(kind=ru["kinds"].get(key, ru["kinds"]["other"]))
            + "\n\n"
            + kk["unsupported_kind"].format(kind=kk["kinds"].get(key, kk["kinds"]["other"])),
        )
    if stage != "ready":
        await stage_prompt(message, p, stage)


