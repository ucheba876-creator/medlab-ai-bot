def get_lock(uid: int) -> asyncio.Lock:
    if uid not in locks:
        locks[uid] = asyncio.Lock()
    return locks[uid]


def trim_history(uid: int) -> None:
    """Оставляем последние MAX_HISTORY сообщений; история должна начинаться с user."""
    h = histories.get(uid, [])
    h = h[-MAX_HISTORY:]
    while h and h[0]["role"] != "user":
        h.pop(0)
    histories[uid] = h


