async def respond_via_claude(
    message: Message,
    bot: Bot,
    p: dict,
    uid: int,
    content,
    reminder: str,
    history_text: str,
    mode: str,
    from_file: bool = False,
) -> None:
    """
    mode: 'analysis' | 'question' | 'cheat'.
    Блокировка пользователя (lock) берётся вызывающим кодом.
    """
    t = TEXTS[p["lang"]]
    wait_msg = await say(message, t["wait"])
    try:
        async with typing_indicator(bot, message.chat.id):
            answer = await ask_claude(uid, content, reminder)

        if mode == "analysis" and answer.strip().upper().startswith("NOT_ANALYSIS"):
            p["offtopic_count"] = p.get("offtopic_count", 0) + 1
            await say(message, offtopic_text(t, p["offtopic_count"], not_analysis=True))
            return

        save_exchange(uid, history_text, answer)

        if mode == "analysis":
            p["has_analysis"] = True
            p["offtopic_count"] = 0
            await send_text(message, answer)
            await say(message, t["after"], reply_markup=cheat_keyboard(p["lang"]))
        elif mode == "question":
            p["offtopic_count"] = 0
            await send_text(message, answer)
        else:  # cheat
            await send_text(message, answer)
    except BadRequestError as e:
        log.exception("Claude API отклонил запрос: %s", e)
        # «файл нечитаем» показываем только если проблема правда в файле, а не в счёте/ключе/модели
        if from_file and is_file_problem(e):
            await say(message, t["file_unreadable"])
        else:
            await say(message, err_text(t, e))
    except Exception as e:
        log.exception("Bot error: %s", describe_error(e))
        await say(message, err_text(t, e))
    finally:
        await drop_message(wait_msg)


async def process_attachment(
    message: Message,
    bot: Bot,
    p: dict,
    *,
    file_obj,
    is_photo: bool,
    filename: str | None,
) -> None:
    """Скачивает файл, проверяет размер/формат и отправляет на разбор (изображение или PDF)."""
    uid = message.from_user.id
    t = TEXTS[p["lang"]]

    lock = get_lock(uid)
    if lock.locked():
        await say(message, t["busy"])
        return

    async with lock:
        try:
            buf = BytesIO()
            try:
                await bot.download(file_obj, destination=buf)
            except Exception:
                log.exception("Не удалось скачать файл из Telegram")
                await say(message, t["photo_error"])
                return
            raw = buf.getvalue()
            if not raw:
                await say(message, t["photo_error"])
                return
            if len(raw) > MAX_FILE_BYTES:
                await say(message, t["file_too_big"])
                return

            media_type = sniff_media_type(raw)
            if media_type is None and is_photo:
                media_type = "image/jpeg"  # Telegram отдаёт сжатые фото как JPEG
            if media_type is None:
                name_part = f" («{filename[:60]}»)" if filename else ""
                await say(message, t["unsupported_file"].format(name=name_part))
                return
            if media_type != "application/pdf" and len(raw) > MAX_IMAGE_API_BYTES:
                await say(message, t["image_api_big"])
                return

            data_b64 = base64.standard_b64encode(raw).decode("utf-8")
            block_type = "document" if media_type == "application/pdf" else "image"
            file_block = {
                "type": block_type,
                "source": {"type": "base64", "media_type": media_type, "data": data_b64},
            }

            caption = (message.caption or "").strip()
            prompt_text = caption if caption else t["file_default"]
            content = [file_block, {"type": "text", "text": prompt_text}]

            # В историю сохраняем только текстовую заметку (без тяжёлых base64)
            history_text = t["file_note"]
            if filename:
                history_text += f" {filename[:80]}"
            if caption:
                history_text += f"\n{caption}"

            await respond_via_claude(
                message, bot, p, uid, content, t["reminder_analysis"], history_text,
                mode="analysis", from_file=True,
            )
        except Exception as e:
            log.exception("Bot error: %s", describe_error(e))
            await say(message, err_text(t, e))


