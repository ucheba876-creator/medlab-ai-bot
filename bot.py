def looks_like_analysis(text: str) -> bool:
    """Эвристика: в тексте есть минимум 2 разных показателя с числами (напр. «Гемоглобин 115, АЛТ 30»)."""
    names = {m.group(1).lower().replace(" ", "") for m in _INDICATOR_RE.finditer(text)}
    return len(names) >= 2


def is_smalltalk(text: str) -> bool:
    return bool(_SMALLTALK_RE.match(text.strip()))


def clean_text(text: str) -> str:
    """Страховка: убирает случайную HTML/Markdown-разметку, если модель её всё же вставила."""
    text = _HTML_TAG.sub("", text)
    text = _MD_BOLD.sub(r"\2", text)
    text = text.replace("`", "")
    text = re.sub(r"^\s{0,3}#{1,6}\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*[*\-]\s+", "• ", text, flags=re.MULTILINE)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def split_text(text: str, limit: int = TG_LIMIT) -> list[str]:
    """Делит длинный ответ на части (не длиннее limit) по границам абзацев/строк/слов."""
    text = text.strip()
    if not text:
        return []
    if len(text) <= limit:
        return [text]
    parts: list[str] = []
    while len(text) > limit:
        cut = text.rfind("\n\n", 0, limit)
        if cut < limit // 2:
            cut = text.rfind("\n", 0, limit)
        if cut < limit // 2:
            cut = text.rfind(" ", 0, limit)
        if cut <= 0:
            cut = limit
        chunk = text[:cut].strip()
        if chunk:
            parts.append(chunk)
        text = text[cut:].strip()
    if text:
        parts.append(text)
    return parts


async def safe_answer(message: Message, text: str, reply_markup=None, retries: int = 3) -> Message:
    """Отправка одного сообщения без parse_mode с повторами при флуд-лимите и сетевых сбоях."""
    last_exc: Exception | None = None
    for attempt in range(retries):
        try:
            return await message.answer(text, parse_mode=None, reply_markup=reply_markup)
        except TelegramRetryAfter as e:
            last_exc = e
            await asyncio.sleep(float(e.retry_after) + 1)
        except TelegramNetworkError as e:
            last_exc = e
            await asyncio.sleep(1 + attempt)
        except TelegramBadRequest:
            log.exception("Telegram отклонил сообщение (длина=%d)", len(text))
            raise
    assert last_exc is not None
    raise last_exc


async def say(message: Message, text: str, reply_markup=None) -> Message | None:
    """Короткое служебное сообщение: НИКОГДА не бросает исключений."""
    try:
        return await safe_answer(message, text, reply_markup)
    except Exception:
        log.exception("Не удалось отправить служебное сообщение")
        return None


async def send_text(message: Message, text: str, reply_markup=None) -> None:
    """Надёжная отправка длинного ответа обычным текстом: части <= TG_LIMIT, клавиатура — на последней."""
    parts = split_text(clean_text(text))
    for i, part in enumerate(parts):
        markup = reply_markup if (i == len(parts) - 1) else None
        await safe_answer(message, part, markup)


def describe_error(exc: BaseException) -> str:
    """Короткое описание ошибки для логов: класс, HTTP-статус и текст от API."""
    status = getattr(exc, "status_code", None)
    msg = str(getattr(exc, "message", "") or exc)
    return f"{type(exc).__name__}" + (f" [{status}]" if status else "") + f": {msg[:300]}"


def error_code(exc: BaseException) -> str:
    """Короткий код ошибки для сообщения пользователю, напр. 'AuthenticationError 401'."""
    status = getattr(exc, "status_code", None)
    return type(exc).__name__ + (f" {status}" if status else "")


def err_text(t: dict, exc: BaseException) -> str:
    """Общее сообщение об ошибке + код, чтобы причину было видно без чтения логов."""
    return f"{t['error']} (код: {error_code(exc)})"


def is_file_problem(exc: BaseException) -> bool:
    """True, если 400 от API действительно про файл, а не про баланс/ключ/модель."""
    msg = str(getattr(exc, "message", "") or exc).lower()
    if any(w in msg for w in ("credit", "balance", "billing", "api key", "model", "quota")):
        return False
    return any(w in msg for w in ("image", "pdf", "document", "media", "base64", "page", "size"))


async def drop_message(msg: Message | None) -> None:
    if msg is None:
        return
    with contextlib.suppress(Exception):
        await msg.delete()


@asynccontextmanager
async def typing_indicator(bot: Bot, chat_id: int):
    """Поддерживает статус «печатает…» всё время, пока идёт запрос к Claude."""

    async def _loop() -> None:
        try:
            while True:
                await bot.send_chat_action(chat_id, "typing")
                await asyncio.sleep(4)
        except asyncio.CancelledError:
            raise
        except Exception:
            return

    task = asyncio.create_task(_loop())
    try:
        yield
    finally:
        task.cancel()
        with contextlib.suppress(asyncio.CancelledError, Exception):
            await task


def sniff_media_type(data: bytes) -> str | None:
    """Определяет реальный тип файла по сигнатуре. None — формат не поддерживается."""
    if data[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    if b"%PDF-" in data[:1024]:
        return "application/pdf"
    return None


def declared_mime(mime_type: str | None, file_name: str | None) -> str | None:
    """Поддерживаемый MIME по заявленному типу/расширению; None — формат не поддерживается."""
    mime = (mime_type or "").lower().strip()
    mime = MIME_ALIASES.get(mime, mime)
    if mime in SUPPORTED_MIME:
        return mime
    ext = Path(file_name or "").suffix.lower()
    if ext in EXT_TO_MIME and mime in ("", "application/octet-stream"):
        return EXT_TO_MIME[ext]
    return None


