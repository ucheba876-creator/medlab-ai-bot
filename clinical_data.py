def fmt_val(v):
    return f"{v:g}"


def marker_status(code, g, v):
    glo, ghi, ylo, yhi = MARKERS[code]["norms"][g]
    if glo <= v <= ghi:
        return "🟢"
    return "🟡" if ylo <= v <= yhi else "🔴"


def marker_range(code, g):
    glo, ghi = MARKERS[code]["norms"][g][:2]
    return f"≤ {fmt_val(ghi)}" if glo == 0 else f"{fmt_val(glo)}–{fmt_val(ghi)}"


def marker_unit(code, lang):
    return MARKERS[code]["unit_kk"] if lang == "kk" else MARKERS[code]["unit"]


def marker_name(code, lang):
    return MARKERS[code]["kk"] if lang == "kk" else MARKERS[code]["ru"]


def get_retest_weeks(code):
    return MARKERS.get(code, {}).get("retest_weeks", 4)


def norms_text(g):
    out = []
    for c, meta in MARKERS.items():
        glo, ghi, ylo, yhi = meta["norms"][g]
        yellow = []
        if ylo < glo:
            yellow.append(f"{fmt_val(ylo)}–{fmt_val(glo)}")
        if ghi < yhi:
            yellow.append(f"{fmt_val(ghi)}–{fmt_val(yhi)}")
        y_str = "/".join(yellow) if yellow else "нет"
        out.append(f"{c}({meta['unit']}):🟢{marker_range(c, g)},🟡{y_str},🔴вне {fmt_val(ylo)}–{fmt_val(yhi)}")
    return "; ".join(out)


def status_text(vals, g):
    parts = []
    for c, v in vals.items():
        if c in MARKERS:
            parts.append(f"{c}={fmt_val(v)} {MARKERS[c]['unit']} {marker_status(c, g, v)} (норма {marker_range(c, g)})")
    return "; ".join(parts) or "нет"


def clean_values(raw):
    out = {}
    if not isinstance(raw, dict):
        return out
    for c in CODES:
        v = raw.get(c)
        if isinstance(v, str):
            m = re.search(r"-?\d+(?:[.,]\d+)?", v)
            v = float(m.group().replace(",", ".")) if m else None
        if isinstance(v, (int, float)) and not isinstance(v, bool) and v >= 0:
            out[c] = float(v)
    return out